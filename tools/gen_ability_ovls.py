#!/usr/bin/env python3
"""Write the split configs of the 35 ability packages (MAIN.CD entries 13-47, docs/overlays.md).

Each package's code block (`make overlays` -> disc/overlays/code/ovlNN.bin, NN its ID word 0x13-0x35) is copied whole
to overlay slot 2 (0x800CAE08, entries 13-41: the Assimilation abilities, docs/abilities.md) or slot 3 (0x800CCB1C,
entries 42-47). They all share their slot's address, so splat names every symbol of a package with its ID
(`symbol_name_format`: func_ovl13_800CAE0C, D_ovl13_800CB95C): no name collides between packages, and the matching
tools find a function without TWINBLADE_OVL.

Layout of a package: the ID word, rodata in front of the code for three packages (TEXT_START), the code to the last
`jr ra` and its delay slot, then data. The code is all -O2.

Writes, for every package:
  abil/ovlNN.yaml                 the splat config (asm/abil/ovlNN/, src/abil/ovlNN.c, build/abil/ovlNN/)
  abil/symbol_addrs_ovlNN.txt     a header naming the package, the names given by hand (kept as they are), then the
                                  outside symbols the package uses (EXE, stage engine, other slots) under their plain
                                  names (func_800183E0): the format would name them func_ovl13_800183E0 too
and prints the table for docs/overlays.md (--table).

--split (`make split-abil`) also runs splat on every config twice: the first pass lists the outside symbols
(build/abil/ovlNN/undefined_*_auto.txt), which go into the symbol file, the second writes the asm with their plain names.
Addresses in the package's own slot (its code, and the bss after it up to the next slot) keep the package's prefix.
`make check-abil` rebuilds and checks every package, `make check-ovlNN` one.

Usage: gen_ability_ovls.py [--split] [--table]
"""
import re
import subprocess
import hashlib
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SLOT2, SLOT3 = 0x800CAE08, 0x800CCB1C
# MAIN.CD entry -> the ability whose package it is (docs/abilities.md: ability, then entry), in ability number order
ABILITY_OF_ENTRY = {
    16: (1, 'Depress'), 21: (2, 'Mint'), 18: (3, 'Satiate'), 22: (4, 'Antidote'), 14: (5, 'Perfume'),
    23: (6, '(6), the cut heal'), 13: (7, 'Stun'), 15: (8, 'Gunshot'), 32: (9, 'D-Kick'), 35: (10, 'Hurl'),
    33: (11, 'Fence'), 20: (12, 'Hop'), 19: (13, 'Shrink'), 25: (15, 'Bowl'), 34: (16, 'Steel'), 17: (17, 'Sleepy'),
    24: (18, '(18), the cut timed ability'), 30: (19, 'Toxin'), 29: (20, 'Rip-off'), 28: (21, 'B.O.'),
    26: (22, 'Firefly'), 36: (23, 'Clone'), 27: (24, 'Sublime'), 37: (25, 'Acid'), 31: (26, 'Map'),
    38: (27, '3-Way'), 39: (28, 'Homing'), 40: (29, 'Grenade'), 41: (30, 'Javelin'),
}
# packages whose code does not start right after the ID word: Bowl and Homing two data words, Steel a jump table
# (Steel's code starts 8 bytes before the table's apparent end: its last two words are the first instructions of
# func_ovl28_800CAE80, r149)
TEXT_START = {0x1F: 0xC, 0x28: 0x78, 0x2D: 0xC}


def packages():
    """[(entry, id, name, slot vram, code bytes)] for the 35 packages"""
    out = []
    for entry in range(13, 48):
        ovl_id = entry + 6                  # entry 13 is ID 0x13 ... entry 47 is ID 0x35
        name = 'ovl%02x' % ovl_id
        path = os.path.join(ROOT, 'disc', 'overlays', 'code', name + '.bin')
        code = open(path, 'rb').read()
        assert struct.unpack_from('<I', code, 0)[0] == ovl_id, path
        out.append((entry, ovl_id, name, SLOT2 if entry <= 41 else SLOT3, code))
    return out


def layout(ovl_id, code):
    """(text start, text end): the code runs to the last `jr ra` and its delay slot"""
    words = struct.unpack_from('<%dI' % (len(code) // 4), code)
    last = max(i for i, w in enumerate(words) if w == 0x03E00008)
    return TEXT_START.get(ovl_id, 4), (last + 2) * 4


def what(entry):
    if entry in ABILITY_OF_ENTRY:
        n, ability = ABILITY_OF_ENTRY[entry]
        return f'ability {n}, {ability}'
    return 'a slot-3 package'


def yaml_text(entry, ovl_id, name, vram, code):
    start, end = layout(ovl_id, code)
    subs = [f'      - [0x0, rodata, {name}_id]     # u32 overlay ID (0x{ovl_id:02X})']
    if start > 4:
        subs.append(f'      - {{start: 0x4, type: data, name: {name}_rodata, linker_section_order: .rodata}} # data in '
                    'front of the code (as data: a rodata jump table\'s cases would be .L labels, docs/decomp_recipes.md 7)')
    subs.append(f'      - [0x{start:X}, c, {name}]            # entry 0x{vram + start:08X}')
    if end < len(code):
        subs.append(f'      - [0x{end:X}, data, {name}_data]')
    sub_text = '\n'.join(subs)
    slot = 2 if vram == SLOT2 else 3
    return f"""# Package 0x{ovl_id:02X}: {what(entry)} (generated by tools/gen_ability_ovls.py; edit the generator, not this file).
# MAIN.CD entry {entry}, the code block of its PAC package (tools/extract_overlays.py -> disc/overlays/code/{name}.bin),
# copied to overlay slot {slot} at 0x{vram:08X}. Symbols carry the package ID (func_{name}_800CAE0C): the packages share
# their slot's address.
name: Package 0x{ovl_id:02X} ({what(entry)})
sha1: {hashlib.sha1(code).hexdigest()}
options:
  basename: {name}
  target_path: disc/overlays/code/{name}.bin
  elf_path: build/abil/{name}/{name}.elf
  base_path: ..
  platform: psx
  compiler: PSYQ

  asm_path: asm/abil/{name}
  src_path: src/abil
  build_path: build
  create_asm_dependencies: True

  ld_script_path: build/abil/{name}/{name}.ld
  ld_dependencies: True
  ld_bss_is_noload: True
  ld_align_section_vram_end: False

  find_file_boundaries: False

  o_as_suffix: True
  use_legacy_include_asm: False

  section_order: [".rodata", ".text", ".data", ".bss"]

  symbol_name_format: {name}_$VRAM
  symbol_name_format_no_rom: {name}_$VRAM

  symbol_addrs_path:
    - symbol_addrs.txt
    - symbol_addrs_psyq.txt
    - abil/symbol_addrs_{name}.txt
  reloc_addrs_path:
    - reloc_addrs.txt

  undefined_funcs_auto_path: build/abil/{name}/undefined_funcs_auto.txt
  undefined_syms_auto_path: build/abil/{name}/undefined_syms_auto.txt

  subalign: 2

  string_encoding: ASCII
  data_string_encoding: ASCII
  rodata_string_guesser_level: 2
  data_string_guesser_level: 2

segments:
  - name: {name}
    type: code
    start: 0x0
    vram: 0x{vram:08X}
    subsegments:
{sub_text}
  - [0x{len(code):X}]
"""


SLOT_END = {SLOT2: SLOT3, SLOT3: 0x800CEDF8}
OUTSIDE_MARK = '// Outside symbols (written by tools/gen_ability_ovls.py --split from the first splat pass)'


def write_symbols(entry, ovl_id, name, vram, outside=None):
    """the package's symbol file: the header, the hand-added lines, then the outside symbols (kept when None)"""
    path = os.path.join(ROOT, 'abil', f'symbol_addrs_{name}.txt')
    hand, old_outside = '', ''
    if os.path.exists(path):
        old = open(path).read()
        body = old.split('\n', 1)[1] if '\n' in old else ''
        hand, _, old_outside = body.partition(OUTSIDE_MARK + '\n')
    if outside is None:
        outside = old_outside
    text = f'// Package 0x{ovl_id:02X} (MAIN.CD entry {entry}, abil/{name}.yaml): {what(entry)}\n' + hand
    if outside:
        text += OUTSIDE_MARK + '\n' + outside
    open(path, 'w', newline='\n').write(text)


def outside_symbols(name, vram):
    """the symbols of the first splat pass outside the package's slot, renamed without the package prefix"""
    lines = []
    for kind in ('funcs', 'syms'):
        path = os.path.join(ROOT, 'build', 'abil', name, f'undefined_{kind}_auto.txt')
        for line in open(path):
            m = re.match(rf'(func|D|jtbl)_{name}_([0-9A-F]{{8}}) = 0x([0-9A-F]{{8}});', line.strip())
            if not m:
                continue
            addr = int(m[3], 16)
            if vram <= addr < SLOT_END[vram]:
                continue
            lines.append((addr, f'{m[1]}_{m[2]} = 0x{m[3]};' + (' // type:func' if m[1] == 'func' else '')))
    return ''.join(l + '\n' for _, l in sorted(set(lines)))


def splat(name):
    r = subprocess.run([sys.executable, '-m', 'splat', 'split', f'abil/{name}.yaml'], cwd=ROOT, capture_output=True,
                       text=True)
    if r.returncode:
        sys.exit(f'splat {name} failed:\n{r.stdout[-2000:]}{r.stderr[-2000:]}')


def main():
    os.makedirs(os.path.join(ROOT, 'abil'), exist_ok=True)
    rows = []
    for entry, ovl_id, name, vram, code in packages():
        open(os.path.join(ROOT, 'abil', name + '.yaml'), 'w', newline='\n').write(yaml_text(entry, ovl_id, name, vram, code))
        if '--split' in sys.argv:
            write_symbols(entry, ovl_id, name, vram, outside='')     # first pass: no outside names
            splat(name)
            write_symbols(entry, ovl_id, name, vram, outside=outside_symbols(name, vram))
            splat(name)
        else:
            write_symbols(entry, ovl_id, name, vram)
        start, end = layout(ovl_id, code)
        rows.append((entry, ovl_id, name, vram, len(code), start, end))
    if '--table' in sys.argv:
        for entry, ovl_id, name, vram, size, start, end in rows:
            print(f'| {name} | {entry} | {what(entry)} | slot {2 if vram == SLOT2 else 3} | {size} B, code 0x{start:X}-0x{end:X} |')
    print(f'{len(rows)} configs written to abil/')


if __name__ == '__main__':
    main()
