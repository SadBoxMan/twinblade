#!/usr/bin/env python3
"""Hourly decomp backup to the external drive (no assets).

Writes F:/Claude/Project Twinblade/decomp_backups/<date>_<time>.zip with the decomp sources (src, include, asm, the splat
configs, symbol and linker files, Makefile, tools without the downloaded toolchains) and the scratch templates in build/work (top level only: its subfolders are the bulk sweep's per-stage drafts), plus a git bundle of the whole
repository history (decomp_backups/repo.bundle, rewritten each time: `git clone repo.bundle` restores every commit).
Keeps the last 48 zips. Prints one line.

Usage: decomp_backup.py [dest dir]
"""
import datetime
import glob
import os
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = sys.argv[1] if len(sys.argv) > 1 else r'F:\Claude\Project Twinblade\decomp_backups'
DIRS = ['src', 'include', 'asm', 'tools', 'build/work']
SKIP = ('tools/toolchain', 'tools/bin', 'tools/psyq_sigs', 'tools/compilers', 'tools/fluidsynth', 'tools/m2c_download',
        'tools/__pycache__',   # downloaded binaries: re-fetchable, not our work
        'asm/stg')             # r145: 139 stage images' splat output (521 MB, 24 570 files), `make split-stg` rewrites it
FILES = ['Makefile', 'slus_007.26.yaml', 'ovl38.yaml', 'symbol_addrs.txt', 'symbol_addrs_psyq.txt', 'reloc_addrs.txt',
         'undefined_syms_extra.txt']


def main():
    if not os.path.isdir(os.path.dirname(DEST)):
        print(f'backup skipped: {os.path.dirname(DEST)} is not available (drive not connected?)')
        return 1
    os.makedirs(DEST, exist_ok=True)
    stamp = datetime.datetime.now().strftime('%Y%m%d_%H%M')
    out = os.path.join(DEST, f'decomp_{stamp}.zip')
    n = 0
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
        for f in FILES:
            p = os.path.join(ROOT, f)
            if os.path.exists(p):
                z.write(p, f)
                n += 1
        for d in DIRS:
            for dp, _, fs in os.walk(os.path.join(ROOT, d)):
                rel = os.path.relpath(dp, ROOT).replace(os.sep, '/')
                if rel.startswith(SKIP):
                    continue
                if rel.startswith('build/work/'):   # r148: per-stage bulk drafts (559 MB, 270k files), regenerated by the sweep
                    continue
                for f in fs:
                    if f.endswith(('.pyc', '.o')):
                        continue
                    p = os.path.join(dp, f)
                    z.write(p, os.path.relpath(p, ROOT))
                    n += 1
    r = subprocess.run(['git', 'bundle', 'create', os.path.join(DEST, 'repo.bundle'), '--all'], cwd=ROOT,
                       capture_output=True, text=True)
    old = sorted(glob.glob(os.path.join(DEST, 'decomp_*.zip')))[:-48]
    for p in old:
        os.remove(p)
    head = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    print(f'backup {out}: {n} files, {os.path.getsize(out) // 1024} KB; repo.bundle at {head}'
          + ('' if r.returncode == 0 else f'; bundle FAILED: {r.stderr.strip()[:200]}'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
