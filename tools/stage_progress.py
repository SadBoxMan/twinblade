#!/usr/bin/env python3
"""Matched / total functions of every stage image's own code (r145, docs/stage_status.md). Read-only: reads src/ only.

The village's own code is src/stage/sc03_001.c (the engine, src/stage/engine*.c, is counted by `make progress` as the
`stage` overlay); every other image is src/stg/<name>.c (stg/<name>.yaml, tools/gen_stage_cfgs.py; r209: with <name>_o0.c and
<name>_post.c where the image has an -O0 run, tools/stage_units.py). In each file a
function is one of:
  C      a definition with a body (matched: `make check-<name>` is byte-identical)
  stub   a definition with an empty body: splat writes these itself for `jr ra; nop`, so they are not decomp work
  asm    an INCLUDE_ASM line, still to match
Matched in C = C; the work done = C - (stubs are counted apart, not in C).

Usage: python -I tools/stage_progress.py            the table and the totals
       python -I tools/stage_progress.py --total    one line (`make progress`)
       python -I tools/stage_progress.py --md       also rewrite docs/stage_status.md (with the "same code" column
                                                    from tools/stage_census.py, about 7 s)
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEF_RE = re.compile(r'^[A-Za-z_][^;=()]*\b(\w+)\s*\([^;]*\)\s*\{\s*$')
KR_RE = re.compile(r'^[A-Za-z_][^;=()]*\b(\w+)\s*\([\w\s,]*\)\s*$')


def kr_body(lines, i):
    """an old-style definition (`f(a)` / `    s32 a;` / `{`, some r132 levers write them): the line of its `{`, or 0"""
    if not KR_RE.match(lines[i]):
        return 0
    k = i + 1
    while k < len(lines) and lines[k][:1] in ' \t' and lines[k].rstrip().endswith(';'):
        k += 1
    return k if k < len(lines) and lines[k].strip() == '{' else 0


def count(path):
    """(C, stub, asm) of one source file: definitions start at column 0 and end at a `}` in column 0"""
    c = stub = asm = 0
    lines = open(path, encoding='utf-8', errors='replace').read().split('\n')
    i = 0
    while i < len(lines):
        l = lines[i]
        if l.startswith('INCLUDE_ASM('):
            asm += 1
        elif (DEF_RE.match(l) or kr_body(lines, i)) and not l.startswith(('typedef', 'struct', 'union', 'enum')):
            j = kr_body(lines, i) or i + 1
            while j < len(lines) and not lines[j].startswith('}'):
                j += 1
            body = '\n'.join(lines[i + 1:j]).strip()
            if body:
                c += 1
            else:
                stub += 1
            i = j
        i += 1
    return c, stub, asm


def stages():
    """[(NAME, [paths])]: the village first, then every split image (r209: a stage with an -O0 run has three files,
    tools/stage_units.py)"""
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import stage_units as U
    out = [('SC03_001', [os.path.join(ROOT, 'src', 'stage', 'sc03_001.c')])]
    for lo in U.stages(ROOT):
        out.append((lo.upper(), U.files(lo, ROOT)))
    return out


def count_all(paths):
    """(C, stub, asm) summed over a stage's files"""
    return tuple(map(sum, zip(*(count(p) for p in paths))))


def same_code():
    """{NAME: [other images with identical own code]} from the census"""
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import stage_census as C
    _, rows, *_ = C.main()
    fam = {}
    for r in rows:
        fam.setdefault(r['fam'], []).append(r['name'])
    return {n: [x for x in v if x != n] for v in fam.values() for n in v}


def main():
    rows = [(n,) + count_all(ps) for n, ps in stages()]
    tc = sum(r[1] for r in rows)
    ts = sum(r[2] for r in rows)
    ta = sum(r[3] for r in rows)
    tot = tc + ts + ta
    work = tc + ta
    full = sum(1 for r in rows if r[3] == 0)
    summary = (f'stage images ({len(rows)}, own code): {tc} / {work} functions matched in C ({100.0 * tc / max(1, work):.1f} %), '
               f'{ta} still asm, plus {ts} empty stubs ({tot} in all); {full} images fully matched')
    if '--total' in sys.argv:
        print(summary)
        return
    print('%-9s %6s %6s %6s %6s %7s' % ('stage', 'funcs', 'C', 'stub', 'asm', 'matched'))
    for n, c, s, a in rows:
        print('%-9s %6d %6d %6d %6d %6.1f%%' % (n, c + s + a, c, s, a, 100.0 * c / max(1, c + a)))
    print(summary)
    if '--md' in sys.argv:
        same = same_code()
        out = ['# Stage status: matched functions per stage image',
               '',
               'Generated by `python -I tools/stage_progress.py --md` (r145); do not edit by hand, rerun it after a stage '
               'pass. Counts the stage\'s own code only (the shared engine is matched once, in src/stage/engine*.c). '
               'C = matched in C (byte-identical, `make check-<stage>`); stub = an empty function splat writes as C '
               '(`jr ra`), not decomp work; asm = INCLUDE_ASM, still to match; matched = C / (C + asm). SC03_001 is '
               'the village (src/stage/sc03_001.c), the others are src/stg/<stage>.c. "Same code as": identical own '
               'code (docs/decomp_census.md): match one, copy its C to the others.',
               '',
               '**' + summary + '.**',
               '',
               '| Stage | Functions | C | Stub | Asm | Matched | Same code as |',
               '|---|---|---|---|---|---|---|']
        for n, c, s, a in rows:
            out.append('| %s | %d | %d | %d | %d | %.1f %% | %s |' % (n, c + s + a, c, s, a, 100.0 * c / max(1, c + a),
                                                                    ' '.join(same.get(n, []))))
        out.append('| **all %d** | %d | %d | %d | %d | %.1f %% | |' % (len(rows), tot, tc, ts, ta, 100.0 * tc / max(1, work)))
        open(os.path.join(ROOT, 'docs', 'stage_status.md'), 'w', newline='\n').write('\n'.join(out) + '\n')
        print('docs/stage_status.md written')


if __name__ == '__main__':
    main()
